"""
find_corner_cases.py

Finds where your headline models (RandomForest, StackingEnsemble -- edit
FOCUS_MODELS below if you mean different ones) underperform OTHER models,
using the prediction_error_vs_*_with_sent.csv files already produced by
iout_ml_exp-ensemble.py --mode full. No retraining, no new data needed.

Two outputs per (target, feature) combination:
  1) bin_level_ranking_<target>_<feature>.csv
     Mean |error| per model at each distinct feature value (bin), with the
     best model at each bin flagged. Rows where a FOCUS_MODEL is NOT the
     best are the "region-level corner cases" -- e.g. "RandomForest loses
     to XGBoost specifically at ConcreteDepth=20".
  2) worst_case_examples_<model>_<target>_<feature>.csv
     The top-N individual test rows with the largest |error| for each
     FOCUS_MODEL -- concrete outlier examples.

Plus one master rollup: corner_case_summary.csv

Run from the same folder as iout_ml_exp-ensemble.py:
    python find_corner_cases.py
"""

import os
import glob
import re
import pandas as pd

OUTPUT_FOLDER = "outputs_ensemble_iout_2026"
FOCUS_MODELS = ["RandomForest", "StackingEnsemble"]   # the models you suspect win on average
TOP_N_WORST = 20                                       # how many worst individual rows to keep

# The (csv, x_column) pairs your training script produces (with_sent only).
# Delay/DropRate were generated by the original run. Throughput/Jitter need
# compute_throughput_jitter_errors.py run once first -- see the check in
# main() below, which tells you exactly which files are still missing.
SOURCE_FILES = [
    ("prediction_error_vs_concrete_depth_Delay_ns_with_sent.csv", "conc_t"),
    ("prediction_error_vs_concrete_depth_DropRate_percent_with_sent.csv", "conc_t"),
    ("prediction_error_vs_concrete_depth_AvgThroughput_kbps_with_sent.csv", "conc_t"),
    ("prediction_error_vs_concrete_depth_Jitter_ns_with_sent.csv", "conc_t"),

    ("prediction_error_vs_VWC_Delay_ns_with_sent.csv", "VWC"),
    ("prediction_error_vs_VWC_DropRate_percent_with_sent.csv", "VWC"),
    ("prediction_error_vs_VWC_AvgThroughput_kbps_with_sent.csv", "VWC"),
    ("prediction_error_vs_VWC_Jitter_ns_with_sent.csv", "VWC"),

    ("prediction_error_vs_b_d_Delay_ns_with_sent.csv", "b_d"),
    ("prediction_error_vs_b_d_DropRate_percent_with_sent.csv", "b_d"),
    ("prediction_error_vs_b_d_AvgThroughput_kbps_with_sent.csv", "b_d"),
    ("prediction_error_vs_b_d_Jitter_ns_with_sent.csv", "b_d"),

    ("prediction_error_vs_soil_d_Delay_ns_with_sent.csv", "soil_d"),
    ("prediction_error_vs_soil_d_DropRate_percent_with_sent.csv", "soil_d"),
    ("prediction_error_vs_soil_d_AvgThroughput_kbps_with_sent.csv", "soil_d"),
    ("prediction_error_vs_soil_d_Jitter_ns_with_sent.csv", "soil_d"),
]


def safe_name(s):
    return (
        str(s).replace(" ", "_").replace("(", "").replace(")", "")
        .replace("/", "_").replace("%", "percent")
    )


def target_from_filename(csv_name, x_col):
    # e.g. "prediction_error_vs_VWC_Delay_ns_with_sent.csv" -> "Delay_ns"
    stem = csv_name.replace(".csv", "")
    stem = stem.replace(f"prediction_error_vs_{x_col}_", "").replace(
        "prediction_error_vs_concrete_depth_", ""
    )
    stem = stem.replace("_with_sent", "")
    return stem


def analyze_one(csv_name, x_col, summary_rows):
    path = os.path.join(OUTPUT_FOLDER, csv_name)
    if not os.path.exists(path):
        print(f"  [SKIP] Not found: {path}")
        return

    df = pd.read_csv(path)
    if "PredictionError" not in df.columns:
        print(f"  [SKIP] No PredictionError column: {csv_name}")
        return
    df["Abs_Error"] = df["PredictionError"].abs()

    target_label = target_from_filename(csv_name, x_col)
    print(f"\n{target_label} vs {x_col}:")

    # ---- 1) Bin-level ranking ----
    bin_means = df.groupby([x_col, "Model"])["Abs_Error"].mean().reset_index()
    pivot = bin_means.pivot(index=x_col, columns="Model", values="Abs_Error")
    pivot["BestModel"] = pivot.idxmin(axis=1)
    pivot["BestModelError"] = pivot.min(axis=1, numeric_only=True)

    out_rank_csv = os.path.join(
        OUTPUT_FOLDER, f"bin_level_ranking_{safe_name(target_label)}_{x_col}.csv"
    )
    pivot.to_csv(out_rank_csv)
    print(f"  Saved: {out_rank_csv}")

    for focus_model in FOCUS_MODELS:
        if focus_model not in pivot.columns:
            continue
        losing_bins = pivot[pivot["BestModel"] != focus_model]
        for x_val, row in losing_bins.iterrows():
            gap = row[focus_model] - row["BestModelError"]
            pct_worse = (gap / row["BestModelError"] * 100) if row["BestModelError"] != 0 else float("nan")
            summary_rows.append({
                "Target": target_label,
                "Feature": x_col,
                "FeatureValue": x_val,
                "FocusModel": focus_model,
                "FocusModelMeanAbsError": row[focus_model],
                "BestModel": row["BestModel"],
                "BestModelMeanAbsError": row["BestModelError"],
                "PercentWorse": pct_worse,
            })
        if not losing_bins.empty:
            print(f"  {focus_model} is NOT the best at {len(losing_bins)} of {len(pivot)} "
                  f"{x_col} value(s) -- see bin_level_ranking CSV / corner_case_summary.csv")
        else:
            print(f"  {focus_model} wins at every {x_col} value in this sweep.")

    # ---- 2) Row-level worst individual examples ----
    for focus_model in FOCUS_MODELS:
        model_df = df[df["Model"] == focus_model]
        if model_df.empty:
            continue
        worst = model_df.sort_values("Abs_Error", ascending=False).head(TOP_N_WORST)
        out_worst_csv = os.path.join(
            OUTPUT_FOLDER,
            f"worst_case_examples_{focus_model}_{safe_name(target_label)}_{x_col}.csv"
        )
        worst.to_csv(out_worst_csv, index=False)
        print(f"  Saved top {len(worst)} worst {focus_model} rows: {out_worst_csv}")


def main():
    missing = [
        name for name, _ in SOURCE_FILES
        if not os.path.exists(os.path.join(OUTPUT_FOLDER, name))
    ]
    if missing:
        print(f"NOTE: {len(missing)} of {len(SOURCE_FILES)} source CSVs not found yet "
              f"(these will be skipped):")
        for name in missing:
            print(f"    {name}")
        if any("AvgThroughput" in m or "Jitter" in m for m in missing):
            print("\nThroughput/Jitter files are missing because they were never generated.")
            print("Run this first, once: python compute_throughput_jitter_errors.py")
        print()

    summary_rows = []
    for csv_name, x_col in SOURCE_FILES:
        analyze_one(csv_name, x_col, summary_rows)

    if summary_rows:
        summary_df = pd.DataFrame(summary_rows).sort_values(
            ["FocusModel", "PercentWorse"], ascending=[True, False]
        )
        out_csv = os.path.join(OUTPUT_FOLDER, "corner_case_summary.csv")
        summary_df.to_csv(out_csv, index=False)
        print(f"\n{'=' * 70}")
        print(f"Saved master corner-case summary: {out_csv}")
        print(f"{'=' * 70}")
        print("\nTop 10 worst corner cases overall (by % worse than best alternative):")
        print(summary_df.head(10).to_string(index=False))
    else:
        print("\nNo corner cases found -- your focus models won every bin in every sweep.")


if __name__ == "__main__":
    main()
